/**
 * «Как это было» — фотографии и отзывы с прошлой поездки в Китай.
 *
 * Фото — из архива команды: страница «Дао-тур в Китай» (telegra.ph, апрель 2026)
 * и кадры, которые прислал организатор; публикацию подтвердил он же.
 * Места подписаны там, где их видно по вывеске или узнаваемой постройке.
 * Отзывов не будет — список пуст, и блок отзывов на сайт не выводится.
 *
 * Как добавить:
 *   1. положите фото в src/assets/photos/, например past-china-01.jpg;
 *   2. допишите его в memoryPhotos: { image: 'past-china-01', alt: 'что на снимке' };
 *   3. отзывы — в reviews: имя, город или род занятий, текст, по желанию фото автора.
 *
 * Раскладка: на телефоне две колонки, на широком экране три. Между широкими
 * кадрами — блоки по 6 или 3 снимка: тогда на компьютере ряды полные, а на телефоне
 * одинокий последний снимок блока Memories.astro растягивает на всю ширину.
 * Пустых клеток нет ни там, ни там.
 */

export interface MemoryPhoto {
  image: string;
  alt: string;
  /** Широкий кадр на всю строку сетки. */
  wide?: boolean;
  /** Точка фокуса при обрезке, например '50% 30%'. */
  focus?: string;
}

export interface Review {
  name: string;
  about?: string;
  text: string;
  /** Ключ фото автора в src/assets/photos, если есть. */
  photo?: string;
}

