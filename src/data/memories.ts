/**
 * «Как это было» — фотографии и отзывы с прошлой поездки в Китай.
 *
 * Фото — из архива команды, со страницы «Дао-тур в Китай» (telegra.ph, апрель 2026).
 * Взяты только кадры, снятые в Китае; места подписаны там, где их видно по вывеске
 * или узнаваемой постройке. Отзывов на той странице нет — ждём от организатора:
 * пустой блок или выдуманные отзывы хуже, чем их отсутствие.
 *
 * Как добавить:
 *   1. положите фото в src/assets/photos/, например past-china-01.jpg;
 *   2. допишите его в memoryPhotos: { image: 'past-china-01', alt: 'что на снимке' };
 *   3. отзывы — в reviews: имя, город или род занятий, текст, по желанию фото автора.
 *
 * Раскладка: на телефоне две колонки, на широком экране три. Широкий кадр стоит
 * после шестого снимка, последний снимок — горизонтальный: на телефоне он
 * растягивается на обе колонки, и в сетке не остаётся дыр.
 */

export interface MemoryPhoto {
  image: string;
  alt: string;
  /** Широкий кадр на всю строку сетки. */
  wide?: boolean;
  /** Точка фокуса при обрезке, например '50% 30%'. */
  focus?: string;
}

export interface Review {
  name: string;
  about?: string;
  text: string;
  /** Ключ фото автора в src/assets/photos, если есть. */
  photo?: string;
}

