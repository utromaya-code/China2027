/**
 * Программа по дням.
 *
 * Состав дней утверждён организатором. Факты, цифры и легенды — из
 * docs/RESEARCH.md; легенды подаются как легенды.
 *
 * Для каждого дня есть «иероглиф дня» — один знак, который держит смысл дня.
 * Знаки попадают в урезанный кистевой шрифт: после правки иероглифов
 * запустите `npm run fonts`.
 */

export type ChapterId = 'south' | 'shangrila' | 'lijiang';

export interface Day {
  n: number;
  id: string;
  chapter: ChapterId;
  date: string;
  dateHuman: string;
  weekday: string;
  place: string;
  placeHanzi: string;
  /** Высота ночёвки или главной точки дня, м — для профиля высот. */
  altitude: number;
  /** Подпись высоты, если главная точка дня не совпадает с ночёвкой. */
  altitudeLabel?: string;
  glyph: { char: string; pinyin: string; meaning: string; line: string };
  title: string;
  text: readonly string[];
  highlights: readonly string[];
  /** Логистика дня одной строкой: поезд, перелёт, переезд. */
  transfer?: string;
  legend?: { title: string; text: string };
  /** Альтернативы, заложенные в программу. */
  options?: { title: string; text: string };
  image: string;
  imageAlt: string;
  gallery?: readonly { image: string; alt: string }[];
}

